th=seq(0,2*pi,length.out=400)
draw=function(){
  par(mfrow=c(1,2),mar=c(4,4,3,1))
  x=2*cos(th)
  y=sin(th)
  plot(x,y,type="l",lwd=2,xlim=c(-2.4,2.4),ylim=c(-1.4,1.4),main="Convex Closed Curve",xlab="x",ylab="y",asp=1)
  for(t0 in c(0.6,2.2,4.0)){
    px=2*cos(t0)
    py=sin(t0)
    dx=-2*sin(t0)
    dy=cos(t0)
    s=seq(-1.6,1.6,length.out=40)
    lines(px+dx*s,py+dy*s,lty=2,col="grey")
  }
  x=cos(2*th)*cos(th)
  y=cos(2*th)*sin(th)
  plot(x,y,type="l",lwd=2,xlim=c(-1.3,1.3),ylim=c(-1.3,1.3),main="Non-Convex Closed Curve",xlab="x",ylab="y",asp=1)
  t0=0.6
  px=cos(2*t0)*cos(t0)
  py=cos(2*t0)*sin(t0)
  dx=-2*sin(2*t0)*cos(t0)-cos(2*t0)*sin(t0)
  dy=-2*sin(2*t0)*sin(t0)+cos(2*t0)*cos(t0)
  s=seq(-1.4,1.4,length.out=40)
  lines(px+dx*s,py+dy*s,lty=2,lwd=1.5)
  points(px,py,pch=19,cex=1.2)
}
pdf("../figures/convex_curve.pdf",width=8,height=4)
draw()
dev.off()
