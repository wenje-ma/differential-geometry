setwd("C:/Users/18904/Github/differential-geometry/codes")
a=0.2
t=seq(0,6*pi,length.out=800)
x=cos(t)
y=sin(t)
z=a*t
proj=function(x,y,z)cbind(0.866*(x-y),0.5*(x+y)-0.8*z)
th=seq(0,2*pi,length.out=80)
mz=seq(0,2*a*pi,length.out=8)
mer_u=c();mer_v=c()
for(k in 0:7){
  ph=k*pi/4
  s=seq(0,2*a*pi,length.out=60)
  mer_u=c(mer_u,proj(rep(cos(ph),60),rep(sin(ph),60),s)[,1])
  mer_v=c(mer_v,proj(rep(cos(ph),60),rep(sin(ph),60),s)[,2])
}
p=proj(x,y,z)
t0=3*pi
c=sqrt(1+a^2)
tp=c(0,-1/c,a/c)
np=c(1,0,0)
bp=c(0,a/c,1/c)
r0=c(cos(t0),sin(t0),a*t0)
L=0.8
draw=function(){
  par(mar=c(0,0,1,0))
  plot(NULL,xlim=c(-2.6,2.6),ylim=c(-4.6,1.4),main="Helix and its Frenet Frame",xlab="",ylab="",asp=1,axes=FALSE)
  for(i in 1:7)lines(proj(cos(th),sin(th),rep(mz[i],80)),lty=2,col="grey")
  for(i in 1:7)lines(cbind(mer_u[((i-1)*60+1):(i*60)],mer_v[((i-1)*60+1):(i*60)]),lty=2,col="grey")
  lines(p,lwd=2)
  pr=proj(r0[1],r0[2],r0[3])
  pe=proj(r0[1]+L*tp[1],r0[2]+L*tp[2],r0[3]+L*tp[3])
  arrows(pr[1],pr[2],pe[1],pe[2],lwd=2,length=0.14)
  pe=proj(r0[1]+L*np[1],r0[2]+L*np[2],r0[3]+L*np[3])
  arrows(pr[1],pr[2],pe[1],pe[2],lwd=2,lty=2,length=0.14)
  pe=proj(r0[1]+L*bp[1],r0[2]+L*bp[2],r0[3]+L*bp[3])
  arrows(pr[1],pr[2],pe[1],pe[2],lwd=2,lty=3,length=0.14)
  text(pe[1],pe[2],"b",pos=4,cex=1.3)
  pe=proj(r0[1]+L*tp[1],r0[2]+L*tp[2],r0[3]+L*tp[3])
  text(pe[1],pe[2],"t",pos=4,cex=1.3)
  pe=proj(r0[1]+L*np[1],r0[2]+L*np[2],r0[3]+L*np[3])
  text(pe[1],pe[2],"n",pos=4,cex=1.3)
}
pdf("../figures/helix.pdf",width=4,height=4)
draw()
dev.off()
svglite::svglite("../figures/helix.svg",width=4,height=4)
